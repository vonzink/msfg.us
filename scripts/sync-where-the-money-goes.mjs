#!/usr/bin/env node
/**
 * Builds the website copy of the "Where the Money Goes" training page, served at /calculators/mbs,
 * from the msfg-calc repo, which is the source of truth. Run it again whenever that page changes:
 *
 *   node scripts/sync-where-the-money-goes.mjs [path-to-msfg-calc]
 *
 * Output: src/calculators/mbs/ with index.html, css/ and js/ (unminified, no inline scripts). Asset URLs are
 * absolute under /calculators/mbs/ so the page works at /calculators/mbs with or without a trailing slash.
 * The route handler at src/app/(marketing)/calculators/mbs/[[...path]]/route.ts reads these files during
 * `next build` and emits them as static responses, so a normal deploy ships them.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.resolve(process.argv[2] || process.env.MSFG_CALC || path.join(ROOT, "..", "msfg-calc"));
const BASE = "/calculators/mbs/";
const OUT = path.join(ROOT, "src", "calculators", "mbs");

const need = (p) => { if (!fs.existsSync(p)) throw new Error("missing source file: " + p); return p; };
const read = (p) => fs.readFileSync(need(p), "utf8");

// Script order matters: utils defines MSFG.*, the LLPA matrix and engine feed the model, the copy module reads the model, the page script runs last.
const JS = ["shared/utils.js", "shared/llpa-matrix.js", "shared/llpa-engine.js", "shared/where-the-money-goes-math.js", "shared/where-the-money-goes-copy.js", "calculators/where-the-money-goes.js"];
const CSS = ["calculators/where-the-money-goes.css"];

let commit = "unknown";
try { commit = execSync("git rev-parse --short HEAD", { cwd: SRC, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { /* not a git checkout */ }

// The EJS view is plain HTML apart from <%# %> comments and the layout's wrapper; strip the comments.
const view = read(path.join(SRC, "views", "calculators", "where-the-money-goes.ejs"));
if (/<%[^#]/.test(view)) throw new Error("the view now contains EJS logic; this script only strips <%# %> comments");
const body = view.replace(/<%#[\s\S]*?%>\s*\n?/g, "");

// Minimal page shell in place of the calculator suite's site layout (header, nav, footer are not copied).
const shellCss = `/* Page shell for the website copy; the page's own styles are all scoped under .wtmg in where-the-money-goes.css. */
:root{--font-body:'Inter',-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;--font-heading:'Poppins','Inter',sans-serif}
*{box-sizing:border-box}
html,body{margin:0;padding:0}
body{font-family:var(--font-body);color:#1F2328;background:#FBFAF7;-webkit-font-smoothing:antialiased}
.calc-page{max-width:1280px;margin:0 auto}
.calc-page__header{padding:32px 24px 16px;border-bottom:1px solid #E2DFD7}
.calc-page__header h1{font-family:var(--font-heading);font-size:28px;line-height:1.2;margin:0 0 8px}
.calc-page__header p{margin:0;max-width:90ch;color:#5E6B78;font-size:15px;line-height:1.5}
.calc-page__body{padding:24px}
@media (max-width:640px){.calc-page__header{padding:24px 16px 12px}.calc-page__header h1{font-size:22px}.calc-page__body{padding:16px 12px}}
`;

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Where the Money Goes | Mountain State Financial Group</title>
  <meta name="description" content="Training page: one loan's money at funding and every month, with a solver for points, comp, servicing value, margin and MBS price. Illustrative figures only.">
  <meta name="robots" content="noindex">
  <!-- Generated by scripts/sync-where-the-money-goes.mjs from msfg-calc ${commit}; edit the msfg-calc files, then rerun the script. -->
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Poppins:wght@600;700&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="${BASE}css/page.css">
  <link rel="stylesheet" href="${BASE}css/where-the-money-goes.css">
</head>
<body>
<main>
${body.trimEnd()}
</main>
${JS.map((f) => `<script src="${BASE}js/${path.basename(f)}"></script>`).join("\n")}
</body>
</html>
`;

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "css"), { recursive: true });
fs.mkdirSync(path.join(OUT, "js"), { recursive: true });
fs.writeFileSync(path.join(OUT, "index.html"), html);
fs.writeFileSync(path.join(OUT, "css", "page.css"), shellCss);
for (const f of CSS) fs.copyFileSync(need(path.join(SRC, "public", "css", f)), path.join(OUT, "css", path.basename(f)));
for (const f of JS) fs.copyFileSync(need(path.join(SRC, "public", "js", f)), path.join(OUT, "js", path.basename(f)));
fs.writeFileSync(path.join(OUT, "SOURCE.txt"), `Generated from msfg-calc commit ${commit} on ${new Date().toISOString().slice(0, 10)} by scripts/sync-where-the-money-goes.mjs.\nServed at ${BASE.replace(/\/$/, "")}. Do not edit these files by hand; change the msfg-calc page and rerun the script.\n`);

const files = fs.readdirSync(OUT).concat(fs.readdirSync(path.join(OUT, "css")).map((f) => "css/" + f), fs.readdirSync(path.join(OUT, "js")).map((f) => "js/" + f));
console.log(`${BASE} built from msfg-calc ${commit}: ${files.length} entries in ${path.relative(process.cwd(), OUT)}`);
